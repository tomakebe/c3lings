#
#  counts[data[i]]++ для i = 0..n-1. Тут две тонкости с размерами.
#
#  1) Индекс — это БАЙТ. Нельзя сделать `mov al, [rdi + rcx]` и сразу
#     использовать rax как индекс: в старших 56 битах rax — мусор.
#     Нужно расширить нулями:
#         movzx eax, byte ptr [rdi + rcx]    # eax = data[i], 0..255
#
#  2) Если в инструкции нет регистра, по которому можно понять размер,
#     его надо назвать явно:
#         inc dword ptr [rdx + rax*4]        # (uint*)counts[eax]++
#     Варианты: byte ptr (1), word ptr (2), dword ptr (4), qword ptr (8).
#     С неправильным размером инструкция ассемблируется, но меняет не те
#     байты: `inc byte ptr` переполнится на 256 и не тронет старшие байты.
#
#  Заметьте, что инструкция может сразу читать и писать память
#  (read-modify-write): `inc dword ptr [..]`, `add [..], eax`. Это всё
#  ещё не атомарно (см. главу 13 про `lock`).
#
#  Функция НЕ обнуляет counts — только прибавляет.
#
#  ЗАДАЧА: исправьте цикл. Программа напечатает
#      a=334 200=133 0=133 1=133 2=134 3=133 255=dead
#
    .intel_syntax noprefix
    .text

    .globl asm_histogram
asm_histogram:
    xor ecx, ecx
    test rsi, rsi
    jz .Ldone
.Lloop:
    mov al, [rdi + rcx]             # TODO: в старших битах rax мусор
    inc byte ptr [rdx + rax*4]      # TODO: счётчики — uint
    inc rcx
    cmp rcx, rsi
    jb .Lloop
.Ldone:
    ret

    .section .note.GNU-stack,"",@progbits
