# =====================================================================
#  a0303 · Циклы
# =====================================================================
#
#  Циклов в ассемблере нет — есть переходы назад. Типичная форма,
#  которую генерируют компиляторы («do-while с проверкой на входе»):
#
#          test rcx, rcx        # цикл выполняется хотя бы раз?
#          jz   .Ldone
#      .Lloop:
#          ...тело...
#          dec  rcx             # dec ставит ZF, когда rcx стал 0
#          jnz  .Lloop          # поэтому cmp не нужен!
#      .Ldone:
#
#  Проверка условия в конце тела экономит один переход на итерацию.
#  `dec`/`inc` ставят ZF/SF/OF (но не CF), так что отдельный cmp с нулём
#  после них лишний.
#
#  Есть и инструкция `loop .Lx` (dec rcx + jnz без флагов), но на
#  современных CPU она медленная — компиляторы её не используют.
#
#  Цикл while (n != 0) { n /= 10; } в asm_count_digits удобно писать
#  как do-while: ведь у нуля тоже одна цифра. Делить будем `div`
#  (вспомните a0203: rdx перед делением обнулить; делитель — регистр).
#
#  Внимание: раннер убьёт программу через 10 секунд — если цикл
#  не завершается, вы увидите «превышено время».
#
#  ЗАДАЧА:
#    asm_sum_to(n)       = 1 + 2 + ... + n  (0 для n = 0) — найдите ошибку;
#    asm_count_digits(n) = число десятичных цифр n — напишите цикл.
#  Программа напечатает
#      sum_to(10)=55 sum_to(100)=5050 digits=1 5 20
#
    .intel_syntax noprefix
    .text

    .globl asm_sum_to
asm_sum_to:
    xor eax, eax
    mov rcx, rdi
    test rcx, rcx
    jz .Ldone
.Lloop:
    add rax, rcx
    dec rcx
    cmp rcx, 1              # TODO: на одну итерацию меньше, чем нужно
    ja .Lloop
.Ldone:
    ret

    .globl asm_count_digits
asm_count_digits:
    # TODO: rax = n, rcx = 10, r8 = счётчик; делите, пока rax != 0
    xor eax, eax
    ret

    .section .note.GNU-stack,"",@progbits
