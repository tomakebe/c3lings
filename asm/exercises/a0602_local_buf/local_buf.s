# =====================================================================
#  a0602 · Локальный массив на стеке
# =====================================================================
#
#  Локальный массив — это просто кусок стека: уменьшаем rsp на нужное
#  число байт, и [rsp] .. [rsp + N - 1] — наши. Освободить — вернуть
#  rsp обратно. Никакого malloc, никакого free; поэтому же нельзя
#  возвращать указатель на локальный массив — после ret эту память
#  займёт кто-то другой.
#
#      sub rsp, 72          # 64 байта массива + 8 на выравнивание
#      mov rdi, rsp         # передать адрес буфера
#      ...
#      add rsp, 72
#
#  Выравнивание считаем так же, как в главе 05: на входе rsp ≡ 8;
#  после `sub rsp, N` нужно rsp ≡ 0 (mod 16), т.е. N ≡ 8 (mod 16).
#  С кадром (push rbp) — наоборот, N кратно 16.
#
#  Красная зона (red zone): System V разрешает листовой функции
#  (не вызывающей других) использовать 128 байт НИЖЕ rsp без `sub rsp`.
#  Обработчики сигналов и прерывания эту зону не трогают. Но как только
#  вы делаете call, сама инструкция call запишет адрес возврата прямо
#  в красную зону — так что здесь она нам не подходит.
#
#  ЗАДАЧА: asm_sum_squares16 заводит массив из 16 int, просит
#  c3_fill(buf, 16) заполнить его квадратами и возвращает сумму
#  элементов. Стек сейчас не выровнен, а цикл суммирования не написан.
#  Программа напечатает
#      sum_squares16=1240 abi=ok
#
    .intel_syntax noprefix
    .text

    .globl asm_sum_squares16
asm_sum_squares16:
    sub rsp, 64             # TODO: выравнивание
    mov rdi, rsp
    mov esi, 16
    call c3_fill
    xor eax, eax
    # TODO: rax = сумма 16 int'ов, лежащих начиная с [rsp]
    add rsp, 64             # TODO
