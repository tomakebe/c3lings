# =====================================================================
#  a0202 · Умножение: imul
# =====================================================================
#
#  У imul три формы:
#
#      imul rax, rsi        # rax = rax * rsi         (2 операнда)
#      imul rax, rsi, 3     # rax = rsi * 3           (3 операнда, immediate)
#      imul rsi             # rdx:rax = rax * rsi     (1 операнд, «широкое»)
#
#  Формы с двумя и тремя операндами дают младшие N бит произведения,
#  и для младших бит знаковое и беззнаковое умножение совпадают —
#  поэтому компиляторы используют imul и для unsigned. Одноадресную
#  форму (и её беззнаковую сестру `mul`) разберём в a0206.
#
#  Умножение на маленькие константы компиляторы часто делают через lea:
#      lea rax, [rdi + rdi*2]   # rax = rdi * 3  (подробно — в главе 04)
#  Но здесь честно используйте imul.
#
#  ЗАДАЧА:
#    asm_area(w, h) = w * h
#    asm_poly(x)    = 3*x*x + 2*x + 1
#  Программа напечатает
#      poly(2)=17 poly(-3)=22 area=42
#
    .intel_syntax noprefix
    .text

    .globl asm_area
asm_area:
    mov rax, rdi
    add rax, rsi            # TODO: это не умножение
    ret

    .globl asm_poly
asm_poly:
    # Подсказка по плану: rax = x*x; rax = rax*3; rcx = x*2; rax += rcx; rax += 1
    mov rax, rdi
    # TODO: допишите вычисление
    ret

    .section .note.GNU-stack,"",@progbits
