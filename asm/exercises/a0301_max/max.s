# =====================================================================
#  a0301 · cmp и условные переходы
# =====================================================================
#
#  `cmp a, b` вычисляет a - b, выбрасывает результат и оставляет только
#  флаги. Следом идёт условный переход jcc: он прыгает на метку, если
#  условие на флагах выполнено, иначе выполнение идёт дальше.
#
#      после cmp a, b:      знаковое     беззнаковое
#        a == b              je           je
#        a != b              jne          jne
#        a <  b              jl           jb   (below)
#        a <= b              jle          jbe
#        a >  b              jg           ja   (above)
#        a >= b              jge          jae
#
#  Запомните: greater/less — знаковые (смотрят SF и OF),
#  above/below — беззнаковые (смотрят CF). Сам `cmp` одинаковый —
#  знаковость выбирается в момент перехода! Ровно эта путаница —
#  классический баг: -1 как беззнаковое — это 0xFFFFFFFF, самое большое.
#
#  Метки вида `1:` — локальные числовые метки GNU as. `jmp 1f` значит
#  «ближайшая метка 1 вперёд (forward)», `1b` — «назад (backward)».
#  Их можно переиспользовать сколько угодно раз.
#
#  ЗАДАЧА: asm_max — максимум двух int, asm_umax — двух uint. Сейчас
#  переходы перепутаны. Программа напечатает
#      max(-5,2)=2 umax=4294967295
#
    .intel_syntax noprefix
    .text

    .globl asm_max
asm_max:
    mov eax, edi            # предполагаем, что a больше
    cmp edi, esi
    ja 1f                   # TODO: a > b — но в каком смысле?
    mov eax, esi            # нет — значит b
1:
    ret

    .globl asm_umax
asm_umax:
    mov eax, edi
    cmp edi, esi
    jg 1f                   # TODO
    mov eax, esi
1:
    ret

    .section .note.GNU-stack,"",@progbits
