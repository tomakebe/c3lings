# =====================================================================
#  a0503 · Вызов функции C3 из ассемблера
# =====================================================================
#
#  `call f` кладёт в стек адрес следующей инструкции и прыгает на f;
#  `ret` снимает этот адрес и прыгает по нему. Чтобы вызвать функцию
#  C3 (или C), нужно соблюдать ABI уже со стороны ВЫЗЫВАЮЩЕГО:
#
#  1. Аргументы — в rdi, rsi, rdx, rcx, r8, r9; результат — в rax.
#
#  2. После call все volatile-регистры (rax, rcx, rdx, rsi, rdi,
#     r8–r11) считаются испорченными. Всё, что должно пережить вызов
#     (указатель на массив, счётчик, сумму), держите в callee-saved
#     регистрах — rbx, r12–r15, — сохранив их старые значения в начале.
#
#  3. Выравнивание стека: перед КАЖДЫМ call значение rsp должно быть
#     кратно 16. Сразу после входа в функцию rsp ≡ 8 (mod 16) — call
#     положил 8-байтовый адрес возврата. Каждый push сдвигает ещё на 8.
#     Считаем: нечётное число push -> выровнено; чётное -> добавьте
#     `sub rsp, 8` (и не забудьте `add rsp, 8` перед pop'ами).
#     Невыровненный стек часто «работает», пока вызываемая функция не
#     выполнит SSE-инструкцию вроде movaps — и тогда segfault.
#
#  Тестовый стенд проверит всё это: c3_weight вызывает harness_trash(),
#  которая проверяет выравнивание и портит volatile-регистры (так может
#  сделать любая функция), а abi_call проверяет callee-saved.
#
#  Имя функции C3 видно ассемблеру, только если у неё есть
#  @export("имя") — см. main.c3.
#
#  ЗАДАЧА: asm_sum_weights(a, n) = сумма c3_weight(a[i]). Текущая
#  версия хранит всё в volatile-регистрах и не выравнивает стек.
#  Программа напечатает
#      sum_weights=1000120 abi=ok
#
    .intel_syntax noprefix
    .text

    .globl asm_sum_weights
asm_sum_weights:
    # TODO: сохраните callee-saved регистры и выровняйте стек
    mov r8, rdi             # TODO: r8, r9, r10 не переживут call
    mov r9, rsi
    xor r10d, r10d          # сумма
    xor ecx, ecx            # TODO: и rcx тоже
.Lloop:
    cmp rcx, r9
    jae .Ldone
    mov edi, [r8 + rcx*4]
    call c3_weight
    add r10, rax
    inc rcx
    jmp .Lloop
.Ldone:
    mov rax, r10
    # TODO: восстановите регистры
    ret

    .section .note.GNU-stack,"",@progbits
