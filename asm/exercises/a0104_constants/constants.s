#  Непосредственный операнд (immediate) в большинстве инструкций x86-64
#  — не больше 32 бит. Когда приёмник 64-битный, процессор расширяет
#  его ЗНАКОВО:
#
#      mov rax, -1       # 48 c7 c0 ff ff ff ff  -> rax = 0xFFFFFFFFFFFFFFFF
#      mov eax, -1       #    b8 ff ff ff ff     -> rax = 0x00000000FFFFFFFF
#
#  Вторая строка пишет в eax, а запись в 32-битный регистр обнуляет
#  старшую половину rax. Одинаковый текст «-1» — разные результаты!
#
#  Единственная инструкция с полным 64-битным immediate — `movabs`
#  (в GNU as можно писать и `mov rax, 0x1122334455667788` — ассемблер
#  сам выберет movabs, если число не влезает в 32 бита со знаком).
#
#  Идиома обнуления регистра — `xor eax, eax`: два байта кода, процессор
#  распознаёт её как «разрыв зависимости», и она обнуляет весь rax.
#  Компиляторы всегда пишут именно её вместо `mov rax, 0`.
#  (Но помните: xor меняет флаги, а mov — нет.)
