# =====================================================================
#  a0105 · Собираем число из байтов (только mov!)
# =====================================================================
#
#  У четырёх «старых» регистров a, b, c, d есть отдельное окно на
#  биты 8..15: ah, bh, ch, dh. Запись в ah меняет ровно второй байт rax:
#
#      rax:  [ ... 48 бит ... | ah | al ]
#
#  Это наследие 16-битного 8086, но иногда удобно. Подвох: ah/bh/ch/dh
#  нельзя закодировать в одной инструкции с регистрами, которым нужен
#  REX-префикс (r8..r15, а также sil, dil, spl, bpl). Попробуйте написать
#  `mov ah, sil` — ассемблер ответит:
#      Error: can't encode register 'ah' in an instruction requiring REX prefix
#  А вот `mov ah, al` или `mov al, dil` — можно.
#
#  Функция объявлена как
#      extern fn uint asm_pack2(char lo, char hi);
#  (char в C3 — беззнаковый байт). lo приходит в dil, hi — в sil, а
#  остальные биты rdi/rsi — мусор, полагаться на них нельзя.
#
#  ЗАДАЧА: напишите asm_pack2, возвращающую hi * 256 + lo, то есть
#  32-битное число 0x0000HHLL. Используйте только mov/movzx (сдвиги будут
#  в главе 08). Убедитесь, что старшие 16 бит eax — нули!
#  Программа напечатает
#      pack2 = 1234 1ff ab00
#
    .intel_syntax noprefix
    .text

    .globl asm_pack2
asm_pack2:
    movzx eax, sil          # eax = 0x000000HH
    mov ah, al              # eax = 0x0000HHHH
    mov al, dil             # eax = 0x0000HHLL
    ret

    .section .note.GNU-stack,"",@progbits
