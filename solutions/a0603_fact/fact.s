# =====================================================================
#  a0603 · Рекурсия: факториал
# =====================================================================
#
#      fact(n) = n == 0 ? 1 : n * fact(n - 1)
#
#  Рекурсивный вызов в ассемблере — обычный call самого себя. Никакой
#  магии: каждый вызов получает свой кусок стека (адрес возврата плюс
#  всё, что функция положила), так что каждая «копия» функции может
#  сохранить там свои значения.
#
#  Вопрос всегда один: что должно пережить вызов? Здесь — n, ведь
#  умножать на него мы будем ПОСЛЕ возврата из fact(n - 1). А rdi —
#  volatile: вызванная функция имеет право (и будет!) его портить.
#
#  Два стандартных решения:
#    * push rdi до вызова, pop после — сохранить в стеке;
#    * держать n в callee-saved rbx: push rbx в начале функции (ведь
#      мы его портим, а он чужой), mov rbx, rdi, ... , pop rbx в конце.
#  Оба меняют rsp на 8 — и, заметьте, выравнивают стек для call.
#
#  ЗАДАЧА: функция почти готова, но значение n теряется при вызове.
#  Программа напечатает
#      fact(5)=120 fact(20)=2432902008176640000
#
    .intel_syntax noprefix
    .text

    .globl asm_fact
asm_fact:
    test rdi, rdi
    jnz .Lrecurse
    mov eax, 1
    ret
.Lrecurse:
    push rbx                # rbx чужой — сохраняем (заодно выравниваем стек)
    mov rbx, rdi            # n переживёт вызов в rbx
    dec rdi
    call asm_fact           # rax = fact(n - 1)
    imul rax, rbx
    pop rbx
    ret

    .section .note.GNU-stack,"",@progbits
