# =====================================================================
#  a0601 · Кадр стека: rbp, пролог и эпилог
# =====================================================================
#
#  Классический пролог и эпилог функции:
#
#      push rbp            # сохранить rbp вызывающего (он callee-saved)
#      mov rbp, rsp        # rbp = «якорь» нашего кадра
#      sub rsp, 32         # место под локальные переменные
#      ...
#      mov rsp, rbp        # освободить локальные (или `leave` — то же
#      pop rbp             #   самое одной инструкцией)
#      ret
#
#  Карта кадра после пролога:
#
#      [rbp + 24]   8-й аргумент (если есть)
#      [rbp + 16]   7-й аргумент
#      [rbp + 8]    адрес возврата
#      [rbp]        сохранённый rbp вызывающего
#      [rbp - 8]    первая локальная переменная
#      [rbp - 16]   вторая ...
#
#  Пока функция работает, rsp может двигаться (push, вызовы), а rbp
#  стоит на месте — удобно и для адресации, и для отладчика: цепочка
#  сохранённых rbp — это и есть backtrace. Компиляторы с -O0 делают
#  так всегда, с оптимизацией — обычно обходятся без rbp
#  (-fomit-frame-pointer) и адресуют локальные через rsp.
#
#  Заметьте выравнивание: на входе rsp ≡ 8 (mod 16), после push rbp
#  rsp ≡ 0, так что `sub rsp, N` с N кратным 16 оставляет стек
#  выровненным.
#
#  ЗАДАЧА:
#    asm_locals(a, b, c) сохраняет аргументы в локальные переменные и
#        считает a*100 + b*10 + c — но эпилог сломан, функция «возвращается»
#        неизвестно куда;
#    asm_seventh(a..g) должна вернуть 7-й аргумент через rbp.
#  Программа напечатает
#      locals=600 seventh=777
#
    .intel_syntax noprefix
    .text

    .globl asm_locals
asm_locals:
    push rbp
    mov rbp, rsp
    sub rsp, 32
    mov [rbp - 8], rdi
    mov [rbp - 16], rsi
    mov [rbp - 24], rdx
    imul rax, [rbp - 8], 100
    imul rcx, [rbp - 16], 10
    add rax, rcx
    add rax, [rbp - 24]
    mov rsp, rbp
    pop rbp
    ret

    .globl asm_seventh
asm_seventh:
    push rbp
    mov rbp, rsp
    mov rax, [rbp + 16]
    pop rbp
    ret

    .section .note.GNU-stack,"",@progbits
