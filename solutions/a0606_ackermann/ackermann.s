# =====================================================================
#  a0606 · Функция Аккермана и хвостовые вызовы
# =====================================================================
#
#      A(0, n) = n + 1
#      A(m, 0) = A(m - 1, 1)
#      A(m, n) = A(m - 1, A(m, n - 1))
#
#  Функция растёт чудовищно быстро и даёт очень глубокую рекурсию:
#  A(3, 7) = 1021, но вложенность вызовов доходит до тысячи с лишним.
#  Каждый уровень стоит вам байтов стека — сколько, зависит от того,
#  сколько вы push'ите.
#
#  Заметьте: во второй и третьей строке ВНЕШНИЙ вызов — хвостовой.
#  Результат A(m - 1, ...) сразу возвращается. Хвостовой вызов самой
#  себя — это просто переход в начало функции с новыми аргументами:
#
#      mov rdi, новое_m
#      mov rsi, новое_n
#      jmp asm_ack            # (или на метку после пролога)
#
#  Без call — значит, без нового кадра стека. Так рекурсия частично
#  превращается в цикл (так делает компилятор с -O2: «tail call
#  elimination»). Настоящий call останется только для внутреннего
#  A(m, n - 1), и сохранять через него нужно лишь m.
#
#  ЗАДАЧА: напишите asm_ack (можно и «в лоб», тремя call — тоже
#  засчитается, если правильно сохраняете регистры). Программа напечатает
#      ack(2,3)=9 ack(3,3)=61 ack(3,7)=1021
#
    .intel_syntax noprefix
    .text

    .globl asm_ack
asm_ack:
    test rdi, rdi
    jnz .Lm_pos
    lea rax, [rsi + 1]      # A(0, n) = n + 1
    ret
.Lm_pos:
    test rsi, rsi
    jnz .Ln_pos
    dec rdi                 # A(m, 0) = A(m - 1, 1) — хвостовой вызов
    mov esi, 1
    jmp asm_ack
.Ln_pos:
    push rbx                # один push: стек выровнен для call
    mov rbx, rdi            # m переживёт вызов
    dec rsi
    call asm_ack            # rax = A(m, n - 1)
    lea rdi, [rbx - 1]
    mov rsi, rax
    pop rbx                 # кадр снят до хвостового перехода
    jmp asm_ack             # A(m - 1, A(m, n - 1))

    .section .note.GNU-stack,"",@progbits
